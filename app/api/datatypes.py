"""HTTP endpoints for ``/api/datatypes`` - Data Types management.

The router owns only HTTP concerns: it receives a validated schema, calls the
matching ``app.crud`` function, and turns a ``None`` result into 404.  Conflicts
raised by ``crud`` are converted centrally by the handlers in ``app.main``.

Called by:
    ``app.main`` through ``app.include_router``.
"""

import uuid

from fastapi import APIRouter, HTTPException, status

from app import crud
from app.api.deps import LimitDep, OffsetDep, SessionDep
from app.constants import DEFAULT_PAGE_SIZE
from app.schemas import DataTypeCreate, DataTypeRead, DataTypeUpdate

router = APIRouter(prefix="/api/datatypes", tags=["Data Types"])


@router.post("", response_model=DataTypeRead, status_code=status.HTTP_201_CREATED)
async def create_data_type(payload: DataTypeCreate, session: SessionDep):
    """Create a new Data Type.

    Args:
        payload: The Data Type to create; the id is generated by the server.
        session: The request-scoped database session.

    Returns:
        DataTypeRead: The created Data Type.
    """
    return await crud.create_data_type(session, payload)


@router.get("", response_model=list[DataTypeRead])
async def list_data_types(session: SessionDep, limit: LimitDep = DEFAULT_PAGE_SIZE, offset: OffsetDep = 0):
    """List Data Types, ordered by name.

    Args:
        session: The request-scoped database session.
        limit: Maximum number of items to return.
        offset: Number of items to skip.

    Returns:
        list[DataTypeRead]: The requested page.
    """
    return await crud.list_data_types(session, limit, offset)


@router.get("/{data_type_id}", response_model=DataTypeRead)
async def get_data_type(data_type_id: uuid.UUID, session: SessionDep):
    """Fetch a single Data Type.

    Args:
        data_type_id: Identifier from the path; a malformed UUID yields 422.
        session: The request-scoped database session.

    Returns:
        DataTypeRead: The requested Data Type.

    Raises:
        HTTPException: 404 if no Data Type has this id.
    """
    data_type = await crud.get_data_type(session, data_type_id)
    if data_type is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "data type not found")
    return data_type


@router.put("/{data_type_id}", response_model=DataTypeRead)
async def update_data_type(
    data_type_id: uuid.UUID, payload: DataTypeUpdate, session: SessionDep
):
    """Replace an existing Data Type.

    Args:
        data_type_id: Identifier of the Data Type to replace.
        payload: The complete new representation.
        session: The request-scoped database session.

    Returns:
        DataTypeRead: The updated Data Type.

    Raises:
        HTTPException: 404 if no Data Type has this id.
    """
    data_type = await crud.update_data_type(session, data_type_id, payload)
    if data_type is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "data type not found")
    return data_type


@router.delete("/{data_type_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_data_type(data_type_id: uuid.UUID, session: SessionDep) -> None:
    """Delete a Data Type that no Data Set references.

    Args:
        data_type_id: Identifier of the Data Type to delete.
        session: The request-scoped database session.

    Raises:
        HTTPException: 404 if no Data Type has this id. A Data Type still in use
            surfaces as 409 through the ConflictError handler.
    """
    if not await crud.delete_data_type(session, data_type_id):
        raise HTTPException(status.HTTP_404_NOT_FOUND, "data type not found")
